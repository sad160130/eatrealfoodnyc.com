export function impressionRestaurantDestination(slug: string): string {
  if (OUTSIDE_NYC.some((token) => slug.includes(token))) return "/healthy-restaurants"
  if (QUEENS.some((token) => slug.includes(token))) return `/nyc/${boroughToSlug("Queens")}/healthy-restaurants`
  return "/healthy-restaurants"
}

export function impression404Redirects(): Array<{ source: string; destination: string; statusCode: 301 }> {
  const restaurant = IMPRESSION_404_RESTAURANT_SLUGS.map((slug) => ({
    source: `/restaurants/${slug}`,
    destination: impressionRestaurantDestination(slug),
    statusCode: 301 as const,
  }))
  return [
    ...restaurant,
    {
      source: "/nyc/manhattan/lower-east-side/vegan-restaurants",
      destination: "/nyc/manhattan/lower-east-side/healthy-restaurants",
      statusCode: 301,
    },
    {
      source: "/nyc/bronx/soundview/healthy-restaurants",
      destination: "/nyc/bronx/healthy-restaurants",
      statusCode: 301,
    },
  ]
}
